# Makes smaller WebP copies of every photo in public/media so phones don't download desktop-sized images.
# Each photo gets name-800.webp and name-1200.webp beside it (when the photo is wider) plus a WebP at its own width,
# and app/ethos/EthosImageSizes.ts records each photo's width so photoSrc() in EthosPath.ts can list the copies.
# Run after adding or replacing a photo:  python scripts/make-image-sizes.py
import json
from pathlib import Path
from PIL import Image

root = Path(__file__).resolve().parent.parent
media = root / 'public' / 'media'
widths = [800, 1200]
sizes = {}

for photo in sorted(media.rglob('*')):
    if photo.suffix.lower() not in ('.jpg', '.jpeg', '.png'):
        continue
    with Image.open(photo) as im:
        im = im.convert('RGB')
        src = '/' + photo.relative_to(root / 'public').as_posix()
        sizes[src] = im.width
        for w in [w for w in widths if w < im.width] + [im.width]:
            out = photo.with_name(f'{photo.stem}-{w}.webp')
            if out.exists() and out.stat().st_mtime > photo.stat().st_mtime:
                continue
            im.resize((w, round(im.height * w / im.width)), Image.LANCZOS).save(out, 'WEBP', quality=78, method=6)
            print('made', out.relative_to(root))

ts = root / 'app' / 'ethos' / 'EthosImageSizes.ts'
ts.write_text(
    '// Generated by scripts/make-image-sizes.py: the width of each photo in public/media.\n'
    f'export const imageWidths: Record<string, number> = {json.dumps(sizes, indent=1)};\n'
    f'export const copyWidths = {json.dumps(widths)};\n',
    encoding='utf-8', newline='\n')
print(f'{len(sizes)} photos recorded in', ts.relative_to(root))
